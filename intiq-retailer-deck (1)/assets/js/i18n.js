(function () {
  const T = window.INTIQ_TEXT;
  const order = ["en", "hi", "mr", "gu"];
  const buttons = [...document.querySelectorAll("#langs button")];
  let cur = "en";
  try { const saved = localStorage.getItem("intiq-lang"); if (T[saved]) cur = saved; } catch (e) {}

  function apply(lang, animate) {
    const run = () => {
      document.documentElement.lang = lang;
      const d = T[lang], en = T.en;
      document.querySelectorAll("[data-i18n]").forEach(el => {
        const k = el.dataset.i18n, v = d[k] !== undefined ? d[k] : en[k];
        if (v === undefined) return;
        if (el.hasAttribute("data-i18n-html")) el.innerHTML = v; else el.textContent = v;
      });
      document.querySelectorAll("[data-i18n-attr]").forEach(el => {
        el.dataset.i18nAttr.split(",").forEach(pair => {
          const [attr, k] = pair.split(":");
          const v = d[k] !== undefined ? d[k] : en[k];
          if (v !== undefined) el.setAttribute(attr, v);
        });
      });
      buttons.forEach(b => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
      document.body.classList.remove("swapping");
      document.dispatchEvent(new CustomEvent("deck:lang", { detail: { lang } }));
    };
    if (animate) { document.body.classList.add("swapping"); setTimeout(run, 280); } else run();
    cur = lang;
    try { localStorage.setItem("intiq-lang", lang); } catch (e) {}
  }

  buttons.forEach(b => b.addEventListener("click", e => { e.stopPropagation(); apply(b.dataset.lang, true); }));
  document.addEventListener("keydown", e => {
    if (e.key === "l" || e.key === "L") apply(order[(order.indexOf(cur) + 1) % order.length], true);
  });
  apply(cur, false);
})();
